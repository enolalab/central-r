#!/usr/bin/env python3
"""Generate THIRD_PARTY_LICENSES.md from `cargo about generate --format json`.

cargo-about groups entries by (license id, license text); identical texts
from different crates still produce separate sections. This script emits
one section per license id, listing every crate that uses it, followed
by the deduplicated license texts.

Usage:
    cargo about generate --format json | scripts/generate-third-party-licenses.py > THIRD_PARTY_LICENSES.md
"""

import json
import sys


def main() -> None:
    data = json.load(sys.stdin)
    licenses = data["licenses"]

    # Collect crates per license id and unique texts per license id.
    crates_by_id = {}
    texts_by_id = {}
    order = []
    for lic in licenses:
        lic_id = lic["id"]
        if lic_id not in crates_by_id:
            crates_by_id[lic_id] = {}
            texts_by_id[lic_id] = {}
            order.append(lic_id)
        for used in lic["used_by"]:
            crate = used["crate"]
            crates_by_id[lic_id][(crate["name"], crate["version"])] = crate.get(
                "repository"
            )
        texts_by_id[lic_id][lic["text"]] = None

    order.sort()

    print("# Third-Party Licenses\n")
    print(
        "Central's binaries incorporate the Rust crates below. Each entry names\n"
        "the crate version and its license; the license texts follow inline. The\n"
        "workspace itself is dual-licensed `MIT OR Apache-2.0` (see\n"
        "`LICENSE-MIT` / `LICENSE-APACHE`).\n"
    )
    print("Generated by `cargo about` against `Cargo.lock`; regenerate with:\n")
    print("```sh")
    print(
        "cargo about generate --format json | scripts/generate-third-party-licenses.py > THIRD_PARTY_LICENSES.md"
    )
    print("```\n")
    print("## Licenses\n")

    for lic_id in order:
        print(f"### {lic_id}\n")
        print("Used by:\n")
        for (name, version), repo in sorted(crates_by_id[lic_id].items()):
            suffix = f" ({repo})" if repo else ""
            print(f"- `{name}` {version}{suffix}")
        print()
        for text in texts_by_id[lic_id]:
            print("```text")
            print(text.strip())
            print("```\n")


if __name__ == "__main__":
    main()
